// What: the page's content security policy, one string for dev and production.
// Why: the camera worker needs a blob: worker, and every other origin stays closed.
// Removed: the window could load remote scripts or connect off this machine.
export function contentSecurityPolicy(): string {
  return [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self'",
    "img-src 'self'",
    "connect-src 'self'",
    "worker-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'none'",
    "frame-src 'none'",
    "form-action 'none'",
  ].join('; ');
}
